// content_texture.rs — 内容纹理的默认配置（S3-3 / F1 决定的**值，不得随手改**）。
//
// 语义（S3-3）：内容纹理层把标记过的场景对象渲染到一张离屏纹理，3D 材质按同一
// `CONTENT_TEXTURE_ID` 采样它 —— 于是"2D 内容贴到 3D 曲面"这条链路不需要任何
// 跨层引用：两侧都只认这个 id。
//
// 为什么在对象层：id 与尺寸是**场景对象的默认配置**（3D 材质、内容相机、录制
// 规格都要用它），属"场景侧声明"，与渲染后端无关。app / 后端都从这里取，
// 避免同一个数字在多处各写一遍（"两处真相"）。
//
// 尺寸选择（F1）：512×512 是 2 的幂、稳定不触发离屏目标反复重建；**正方形**与
// 参数曲面域 `[-1.5, 1.5]²` 同比，避免贴图被非等比拉伸。

/// 内容纹理句柄 id：3D 材质与内容层录制用同一个值（唯一真相）。
pub const CONTENT_TEXTURE_ID: u64 = 1;

/// 内容纹理宽（物理像素）。
pub const CONTENT_TEXTURE_WIDTH: u32 = 512;

/// 内容纹理高（物理像素）。
pub const CONTENT_TEXTURE_HEIGHT: u32 = 512;
